def _phrase_contains_word(word: str, phrase: str) -> bool:
    """Check target word appears as whole word or common inflection."""
    phrase_l = phrase.lower()
    word_l = word.lower()
    if re.search(rf"\b{re.escape(word_l)}\b", phrase_l):
        return True
    if word_l.endswith("e"):
        stems = [word_l, word_l + "d", word_l + "ing", word_l[:-1] + "ing", word_l + "s"]
    elif word_l.endswith("y") and len(word_l) > 2 and word_l[-2] not in "aeiou":
        stem = word_l[:-1]
        stems = [word_l, stem + "ies", stem + "ied", word_l + "ing", word_l + "s"]
    else:
        stems = [word_l, word_l + "s", word_l + "es", word_l + "ed", word_l + "ing"]
    for stem in stems:
        if re.search(rf"\b{re.escape(stem)}\b", phrase_l):
            return True
    return False


def verify_coverage() -> str:
    """Validate COLLOCATIONS covers all top-500 base words."""
    expected = load_top500_base_words()
    expected_set = set(expected)
    actual_set = set(COLLOCATIONS.keys())
    missing = sorted(expected_set - actual_set)
    extra = sorted(actual_set - expected_set)
    issues: list[str] = []
    if missing:
        issues.append(f"missing words: {', '.join(missing)}")
    if extra:
        issues.append(f"extra words: {', '.join(extra)}")
    for word in expected:
        items = COLLOCATIONS.get(word, [])
        if word not in COLLOCATIONS:
            issues.append(f"{word}: not in COLLOCATIONS")
            continue
        if len(items) > 3:
            issues.append(f"{word}: more than 3 items")
        if word in EMPTY_PRONOUNS and items:
            issues.append(f"{word}: pronoun should be empty")
        for en, zh in items:
            if not en.strip() or not zh.strip():
                issues.append(f"{word}: empty en/zh")
            if not _phrase_contains_word(word, en):
                issues.append(f"{word}: phrase missing word: {en}")
    total_phrases = sum(len(COLLOCATIONS.get(w, [])) for w in expected)
    if issues:
        return f"FAIL: {len(expected)} words, {total_phrases} phrases, {len(issues)} issues\n" + "\n".join(issues)
    return f"OK: {len(expected)} words, {total_phrases} phrases, 0 issues"
