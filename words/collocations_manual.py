def normalize_key(word: str) -> str:
    w = word.strip().lower()
    w = re.sub(r"\s*\([^)]*\)", "", w)
    w = re.sub(r"\s*=.*$", "", w)
    w = re.sub(r"\s+modal\s*$", "", w, flags=re.I)
    return w.strip().rstrip(".")


def load_top500_base_words(path: Path = TOP500_PATH) -> list[str]:
    """Return sorted unique normalized base words from _top500_words.json."""
    raw = json.loads(path.read_text(encoding="utf-8"))
    seen: set[str] = set()
    words: list[str] = []
    for item in raw:
        key = normalize_key(item["word"])
        if key not in seen:
            seen.add(key)
            words.append(key)
    return sorted(words)


